// Prompts for the engine steps. Kept separate so they are easy to iterate on.

function bookLine(b) {
  const bits = [b.review && `MY REVIEW: ${String(b.review).slice(0, 700)}`, b.notes && `MY NOTES: ${String(b.notes).slice(0, 300)}`].filter(Boolean);
  return `${b.rating ? b.rating + '★ ' : ''}${b.title}${b.series ? ' [' + b.series + ']' : ''} — ${b.author}` +
    `${b.year ? ' (' + b.year + ')' : ''}${b.pages ? ', ' + b.pages + 'pp' : ''}${bits.length ? '\n   ' + bits.join('\n   ') : ''}`;
}
const compactLine = b => `${b.rating ? b.rating + '★ ' : ''}${b.title} — ${b.author}${b.year ? ' (' + b.year + ')' : ''}`;

// full = true includes reviews and notes (used for the taste profile); otherwise one short line per book.
export function libraryText(lib, full = false) {
  const g = s => lib.filter(b => b.shelf === s);
  const line = full ? bookLine : compactLine;
  const block = (title, rows) => `${title}:\n${rows.map(line).join('\n') || '(none)'}`;
  return [
    block('READ & RATED (out of 5; 0 = unrated)', [...g('read')].sort((a, b) => b.rating - a.rating)),
    block('DID NOT FINISH', g('did-not-finish')),
    block('CURRENTLY READING', g('currently-reading')),
    block("TO-READ (already on the reader's list)", g('to-read')),
  ].join('\n\n');
}

export function profilePrompt(lib) {
  return `You are the taste analyst for a book recommender. Below is one reader's Goodreads library. Write a concise taste profile (150-220 words, plain prose, second person "you") covering:
1. What they value, framed as what books ARGUE or explore, not genre labels (e.g. whether an author believes in human ingenuity vs. pessimism about the limits of knowledge; ideas, explanation, epistemology, society-building).
2. Style and narrative voice they respond to, and what they dislike (infer from low ratings, DNFs, reviews and notes).
3. One or two interesting tensions or gaps in their taste.
Use their own reviews and notes as strong evidence. Do not invent books they have not listed. Output only the profile text.

${libraryText(lib, true)}`;
}

// The shelves shown in the shop. Each is generated by its own (parallel) call.
export const SHELVES = [
  { title: 'From your to-read pile', blurb: 'Already on your list, ranked by what to read next.', count: 8, fromToRead: true,
    rule: 'Pick from the TO-READ list only, using the exact title and author as listed. Rank them: best next read first.' },
  { title: 'Closest fit', blurb: 'New books that sit closest to what you rate highest.', count: 14,
    rule: 'New books (not in the library at all) that sit closest to the reader\'s highest-rated books on underlying ideas and narrative voice.' },
  { title: 'Stretch', blurb: 'Same underlying ideas, different genre, era or form.', count: 10,
    rule: 'New books that share the reader\'s underlying ideas but come from a different genre, era or form (non-fiction allowed where it fits).' },
  { title: 'Wildcards', blurb: 'Surprising picks with a non-obvious link to your taste.', count: 8,
    rule: 'Surprising new books with a strong but non-obvious link to the reader\'s taste.' },
];

const steerBlock = ({ profile = '', steer = [], pinned = [], dismissed = [] }) => `TASTE PROFILE (reader-edited, authoritative):
${profile}

STEERING: ${steer.length ? steer.join('; ') : 'none'}
PINNED (liked from earlier picks; do not repeat): ${pinned.join('; ') || 'none'}
DISMISSED (do not suggest): ${dismissed.join('; ') || 'none'}`;

export function shelfPrompt(body, idx) {
  const s = SHELVES[idx];
  return `You are the engine behind a personal bookshop. Fill ONE shelf of recommendations for this reader.

SHELF: "${s.title}" — exactly ${s.count} books. ${s.rule}

RULES
- Only REAL, well-known published books you are confident exist, with the correct author. If unsure a book exists, leave it out; never invent titles. (Every title is checked against a real catalogue and dropped if not found.)
- ${s.fromToRead ? 'Every book must come from the TO-READ list.' : 'Do NOT recommend anything already in the library (read, DNF, currently reading or to-read).'}
- Link on underlying ideas, themes and narrative voice, not genre, popularity or "readers also liked". Respect the steering below.
- "pitch" is a hook of at most 12 words saying what ties it to this reader.

OUTPUT: JSON only, no commentary: [{"title":"","author":"","year":"","pitch":""}]

${steerBlock(body)}

LIBRARY:
${libraryText(body.library)}`;
}

export function explainPrompt({ library, profile = '', book }) {
  return `You are the engine behind a personal bookshop. Explain why this book was recommended to this reader.

BOOK: ${book.title} — ${book.author}${book.year ? ' (' + book.year + ')' : ''}

Write JSON only, no commentary:
{"why":"<2-3 sentences: which of the reader's own library books it connects to, what is shared (ideas, themes, narrative voice), and where this author's take DIFFERS (e.g. optimistic vs pessimistic about human ingenuity)>","links":["<exact titles of library books it connects to>"],"themes":["<2-3 short theme tags>"],"caution":"<one short line on where it may not land for this reader>"}

Be honest and specific. Only name books that are in the library below.

TASTE PROFILE:
${profile}

LIBRARY:
${libraryText(library)}`;
}
